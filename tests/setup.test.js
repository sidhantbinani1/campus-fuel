import { test } from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { mountSetup } from '../src/setup.js';

test('setup searches schools, defaults to public nicknames, supports opting out, and retains form after a save failure', async () => {
  const dom = new JSDOM('<main id="setup"></main>');
  globalThis.document = dom.window.document;
  const el = document.querySelector('main');
  let calls = 0;
  mountSetup(el, { schools: [{ name:'Cal Poly San Luis Obispo', menus:true }, {name:'San Diego State University', menus:false}], onSignout(){}, async onSave(){ calls++; throw Error('Please retry saving.'); } });
  const school=el.querySelector('#school-search');
  school.value='San';school.dispatchEvent(new dom.window.Event('input'));
  assert.equal(el.querySelectorAll('[role=option]').length,2);
  school.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'ArrowDown',cancelable:true}));
  school.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Enter',cancelable:true}));
  assert.equal(school.value,'Cal Poly San Luis Obispo');
  assert.equal(el.querySelector('#setup-schools').hidden,true);
  assert.equal(el.querySelector('#hide-nickname').checked,false);
  const participating=el.querySelector('#participating');participating.checked=true;participating.dispatchEvent(new dom.window.Event('change'));
  assert.equal(el.querySelector('#nickname').required,true);
  assert.equal(el.querySelector('form').checkValidity(),false);
  el.querySelector('#nickname').value='CampusFox';
  el.querySelector('#accept-terms').checked=true;
  const event=()=>new dom.window.Event('submit',{cancelable:true});
  el.querySelector('form').dispatchEvent(event());
  el.querySelector('form').dispatchEvent(event());
  await new Promise(r=>setTimeout(r,0));
  assert.equal(calls,1,'prevent duplicate saves');
  assert.equal(el.querySelector('#setup-error').textContent,'Please retry saving.');
  assert.equal(el.querySelector('#nickname').value,'CampusFox');
  assert.equal(el.querySelector('.setup-submit').disabled,false);
  el.querySelector('[value=no]').checked=true;
  el.querySelector('[value=no]').dispatchEvent(new dom.window.Event('change'));
  assert.equal(el.querySelector('#show-nickname').checked,false);
  assert.equal(el.querySelector('#nickname').disabled,true);
  assert.equal(el.querySelector('form').checkValidity(),true);
  dom.window.close();
});
